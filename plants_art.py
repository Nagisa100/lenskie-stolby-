def _grey(c):
    
    v = 0.3*c[0] + 0.59*c[1] + 0.11*c[2]
    k = int(58 + 0.55*v)
    return (k, k + 8, k)


def palette(name, grey=False):
    pal = dict(BASE)
    pal.update(PLANT_ART[name].get("pal", {}))
    return {k: _grey(v) for k, v in pal.items()} if grey else pal


def plant_sprite(sp, sway=0, big=False, grey=False):
    
    art = PLANT_ART.get(sp["name"])
    if not art:
        return assets.flower(sp["base"], sp["light"], grey=grey, sway=0 if big else sway)
    pal = palette(sp["name"], grey)
    grid = art["card" if big else "map"]
    head = 0 if big else art.get("head", 0)
    w, h = max(len(r) for r in grid), len(grid)
    img = Image.new("RGBA", (w + 4, h + 2), (0, 0, 0, 0))  # поля под качание и обводку
    assets._draw_grid(img, grid[:head], pal, 2 + sway, 1)
    assets._draw_grid(img, grid[head:], pal, 2, 1 + head)
    return assets.add_outline(img)


def check_art():
    
    from species import SPECIES
    problems = []
    for sp in SPECIES:
        art = PLANT_ART.get(sp["name"])
        if not art:
            problems.append(f"нет арта: {sp['name']}")
            continue
        pal = palette(sp["name"])
        for key, (mw, mh) in (("map", MAP_MAX), ("card", CARD_MAX)):
            grid = art[key]
            w, h = max(len(r) for r in grid), len(grid)
            if w > mw or h > mh:
                problems.append(f"{sp['name']}: {key} {w}x{h} больше {mw}x{mh}")
            bad = {ch for row in grid for ch in row if ch != '.' and ch not in pal}
            if bad:
                problems.append(f"{sp['name']}: {key} — нет в палитре {''.join(sorted(bad))}")
    extra = set(PLANT_ART) - {sp["name"] for sp in SPECIES}
    if extra:
        problems.append("арт без вида: " + ", ".join(sorted(extra)))
    return problems
